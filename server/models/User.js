const mongoose = require("mongoose");

const userSchema = new mongoose.Schema({
  name: {
    type: String,
    required: true,
  },
  email: {
    type: String,
    required: true,
    unique: true,
  },
  password: {
    type: String,
    required: true,
  },
}, { timestamps: true });

// CRITICAL FIX: Make sure you are exporting the compiled Mongoose model!
module.exports = mongoose.model("User", userSchema);
